#git init     Создает локальный репозиторий
#git add .    Добавляет все файлы и папки в локальный репозиторий
#git commit -m "Комментарий"        Фиксирует изменения (создает новую версию проекта)
#git branch -M main           Указываем что работаем в основной ветке
#git remote add origin [ссылка_на_проект]         Связывает локальный репозиторий с репозиторием на GitHub
#git push           Отправляет изменения на GitHub